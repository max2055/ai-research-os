INDEX_PATHS = {
    "source": Path("08_Indexes/Source_Index.md"),
    "event": Path("08_Indexes/Event_Index.md"),
    "thesis": Path("08_Indexes/Thesis_Index.md"),
    "company": Path("08_Indexes/Company_Index.md"),
    "impact_assertion": Path("08_Indexes/Impact_Index.md"),
}


def display(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, list):
        return ", ".join(str(item) for item in value)
    if isinstance(value, float):
        return f"{value:.2f}"
    return str(value)


def index_date(objects: list[ResearchObject]) -> str:
    values = [
        str(obj.metadata.get("updated_at"))
        for obj in objects
        if obj.object_type != "job"
        if is_iso_date(obj.metadata.get("updated_at"))
    ]
    return max(values, default=date.today().isoformat())


def index_header(title: str, objects: list[ResearchObject]) -> list[str]:
    return [
        f"# {title}",
        "",
        "<!-- Generated by 09_Automation/research_os.py index. -->",
        "",
        f"更新时间：{index_date(objects)}",
        "",
    ]


def render_source_index(objects: list[ResearchObject]) -> str:
    rows = sorted(
        (obj for obj in objects if obj.object_type == "source"),
        key=lambda obj: obj.object_id,
    )
    lines = index_header("Source Index", rows)
    lines += [
        "| Source ID | 标题 | 类型 | 发布者 | 等级 | 归档状态 | 审核状态 |",
        "|---|---|---|---|---|---|---|",
    ]
    for obj in rows:
        meta = obj.metadata
        lines.append(
            "| "
            + " | ".join(
                (
                    obj.object_id,
                    display(meta.get("title")),
                    display(meta.get("source_type")),
                    display(meta.get("publisher")),
                    display(meta.get("source_grade")),
                    display(meta.get("processing_status")),
                    display(meta.get("review_status")),
                )
            )
            + " |"
        )
    return "\n".join(lines) + "\n"


