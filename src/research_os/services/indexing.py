def render_home_dashboard(objects: list[ResearchObject]) -> str:
    projects = sorted(
        (obj for obj in objects if obj.object_type == "project"),
        key=lambda obj: obj.object_id,
    )
    pending = sorted(
        (obj for obj in objects if obj.metadata.get("review_status") == "pending"),
        key=lambda obj: (obj.object_type, obj.object_id),
    )
    actions = sorted(
        (
            obj
            for obj in objects
            if obj.object_type == "action"
            and obj.metadata.get("status") in {"open", "in_progress"}
        ),
        key=lambda obj: (str(obj.metadata.get("due_date")), obj.object_id),
    )
    theses = sorted(
        (obj for obj in objects if obj.object_type == "thesis"),
        key=lambda obj: obj.object_id,
    )
    reports = sorted(
        (obj for obj in objects if obj.object_type == "report"),
        key=lambda obj: str(obj.metadata.get("updated_at", "")),
        reverse=True,
    )
    failed_jobs = sorted(
        (
            obj
            for obj in objects
            if obj.object_type == "job" and obj.metadata.get("status") == "failed"
        ),
        key=lambda obj: str(obj.metadata.get("started_at", "")),
        reverse=True,
    )
    lines = index_header("AI Research OS Home", objects)
    lines += [
        "> Obsidian fallback dashboard. Rebuilt from canonical Markdown objects.",
        "",
        "## Projects",
        "",
    ]
    lines.extend(
        f"- [[{obj.object_id}]] — {display(obj.metadata.get('title'))} · "
        f"{display(obj.metadata.get('status'))} · next review "
        f"{display(obj.metadata.get('next_review_date'))}"
        for obj in projects
    )
    if not projects:
        lines.append("- None")
    lines += [
        "",
        "## Review queue",
        "",
        "| Object | Type | Updated |",
        "|---|---|---|",
    ]
    lines.extend(
        f"| [[{obj.object_id}]] | {obj.object_type} | "
        f"{display(obj.metadata.get('updated_at'))} |"
        for obj in pending
    )
    if not pending:
        lines.append("| — | No pending objects | — |")
    lines += [
        "",
        "## Thesis health",
        "",
        "| Thesis | Confidence | Supporting | Contradicting |",
        "|---|---:|---:|---:|",
    ]
    lines.extend(
        f"| [[{obj.object_id}]] | {display(obj.metadata.get('confidence'))} | "
        f"{len(obj.metadata.get('supporting_evidence', []))} | "
        f"{len(obj.metadata.get('contradicting_evidence', []))} |"
        for obj in theses
    )
    if not theses:
        lines.append("| — | — | — | — |")
    lines += [
        "",
        "## Open actions",
        "",
        "| Action | Owner | Due | Status |",
        "|---|---|---|---|",
    ]
    lines.extend(
        f"| [[{obj.object_id}]] | {display(obj.metadata.get('owner'))} | "
        f"{display(obj.metadata.get('due_date'))} | "
        f"{display(obj.metadata.get('status'))} |"
        for obj in actions
    )
    if not actions:
        lines.append("| — | — | — | No open actions |")
    lines += [
        "",
        "## Recent reports",
        "",
    ]
    lines.extend(
        f"- [[{obj.object_id}]] — {display(obj.metadata.get('title'))} · "
        f"{display(obj.metadata.get('status'))}"
        for obj in reports[:10]
    )
    if not reports:
        lines.append("- None")
    lines += [
        "",
        "## Failed jobs",
        "",
    ]
    lines.extend(
        f"- [[{obj.object_id}]] — {display(obj.metadata.get('job_name'))}: "
        f"{display(obj.metadata.get('message'))}"
        for obj in failed_jobs[:10]
    )
    if not failed_jobs:
        lines.append("- None")
    return "\n".join(lines) + "\n"


def render_indexes(objects: list[ResearchObject]) -> dict[Path, str]:
    return {
        INDEX_PATHS["source"]: render_source_index(objects),
        INDEX_PATHS["event"]: render_event_index(objects),
        INDEX_PATHS["thesis"]: render_thesis_index(objects),
        INDEX_PATHS["company"]: render_company_index(objects),
        INDEX_PATHS["impact_assertion"]: render_impact_assertion_index(objects),
        Path("05_Research/Project_Registry.md"): render_project_registry(objects),
        Path("05_Research/Reviews/Action_Register.md"): render_action_register(objects),
        Path("08_Indexes/Review_Index.md"): render_review_index(objects),
        Path("08_Indexes/Home_Dashboard.md"): render_home_dashboard(objects),
    }


def render_project_indexes(
    objects: list[ResearchObject],
    project_id: str,
) -> dict[Path, str]:
    if not any(
        obj.object_type == "project" and obj.object_id == project_id for obj in objects
    ):
        raise ValueError(f"unknown project id {project_id}")
    scoped = [
        obj
        for obj in objects
        if obj.object_id == project_id
        or project_id in obj.metadata.get("project_ids", [])
    ]
    prefix = Path("08_Indexes/Projects") / project_id
    return {
        prefix / path.name: content for path, content in render_indexes(scoped).items()
    }


def index_drift(root: Path, rendered: dict[Path, str]) -> list[Path]:
    drift: list[Path] = []
    for relative, expected in rendered.items():
        path = root / relative
        try:
            actual = path.read_text(encoding="utf-8")
        except FileNotFoundError:
            actual = ""
        if actual != expected:
            drift.append(relative)
    return drift


def apply_indexes(root: Path, rendered: dict[Path, str]) -> None:
    transaction = FileTransaction(root)
    for relative, content in rendered.items():
        if (root / relative).exists():
            transaction.stage_replace(relative, content)
        else:
            transaction.stage_create(relative, content)
    transaction.commit()
