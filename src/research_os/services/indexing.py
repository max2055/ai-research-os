def render_thesis_index(objects: list[ResearchObject]) -> str:
    rows = sorted(
        (obj for obj in objects if obj.object_type == "thesis"),
        key=lambda obj: obj.object_id,
    )
    lines = index_header("Thesis Index", rows)
    lines += [
        "| Thesis ID | 判断 | 置信度 | 支持 | 反面 | Thesis 状态 | 审核状态 |",
        "|---|---|---:|---:|---:|---|---|",
    ]
    for obj in rows:
        meta = obj.metadata
        supporting = meta.get("supporting_evidence", [])
        contradicting = meta.get("contradicting_evidence", [])
        lines.append(
            "| "
            + " | ".join(
                (
                    obj.object_id,
                    display(meta.get("title")),
                    display(meta.get("confidence")),
                    str(len(supporting) if isinstance(supporting, list) else 0),
                    str(len(contradicting) if isinstance(contradicting, list) else 0),
                    display(meta.get("thesis_status")),
                    display(meta.get("review_status")),
                )
            )
            + " |"
        )
    lines += [
        "",
        "说明：支持和反面数量来自 Thesis front matter；contextual Event 不计入。",
    ]
    return "\n".join(lines) + "\n"


